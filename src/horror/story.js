// 이번 판의 단서 글 세 장. 첫째, 둘째, 셋째 자리 순서다
export function clueTexts(mapId, code) {
  const c = CLUES[mapId];
  const fill = (lines) => lines.map((t) => t.replaceAll('{a}', code.digits[0]).replaceAll('{n}', code.add));
  return [fill(c.first), fill(c.second), fill(code.same ? c.same : c.less)];
}

