// 쪽지를 읽는 동안 괴물은 멈추지 않는다. 읽는 사람에게 알려 주는 작은 줄
export const NOTE_DANGER_LINE = '읽는 동안에도 {name}는 가까이 있어요';

const JOSA = { 는: '은', 가: '이', 를: '을' };
const hasFinal = (s) => {
  const c = s.charCodeAt(s.length - 1);
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
};

// {name} 을 괴물 이름으로 바꾼다. 글에는 받침 없는 이름처럼 {name}는, {name}가, {name}를 로 쓰면 받침에 맞게 고친다.
// {other} 는 둘째 괴물 이름이고 쓰는 법은 같다. 글 하나 또는 글 여러 줄을 받는다.
export function fillName(text, name, other = name) {
  if (Array.isArray(text)) return text.map((t) => fillName(t, name, other));
  return text.replace(/\{(name|other)\}(는|가|를)?/g, (_, who, j) => {
    const shown = who === 'name' ? name : other;
    return shown + (j && hasFinal(shown) ? JOSA[j] : j ?? '');
  });
}

// 괴물이 둘이면 '세이노와 눈뜬이' 처럼 잇는다
export function joinNames(names) {
  return names.reduce((all, name) => `${all}${hasFinal(all) ? '과' : '와'} ${name}`);
}
